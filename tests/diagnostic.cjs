const assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path'), crypto = require('node:crypto');
const D = require('../modules/diagnostic');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'oasis-diag-'));
const ecrire = (f, t) => { fs.mkdirSync(path.dirname(path.join(dir, f)), { recursive: true }); fs.writeFileSync(path.join(dir, f), t); };
const h = t => crypto.createHash('sha1').update(t).digest('hex').slice(0, 16);
ecrire('package.json', '{"version":"9.9.9"}');
assert.equal(D.analyser(dir).manifeste, false, 'sans manifeste : pas de diagnostic');
ecrire('server.js', 'A'); ecrire('modules/a.js', 'B'); ecrire('public/app.js', 'C'); ecrire('data/db.json', '{}');
ecrire('manifeste.json', JSON.stringify({ version: '9.9.9', nombre: 4, fichiers: { 'package.json': h('{"version":"9.9.9"}'), 'server.js': h('A'), 'modules/a.js': h('B'), 'public/app.js': h('C'), 'public/quiz.js': h('D') } }));
let r = D.analyser(dir);
assert.deepEqual([r.complet, r.manquants, r.differents, r.enTrop], [false, ['public/quiz.js'], [], []]);
ecrire('public/quiz.js', 'D'); ecrire('public/app.js', 'ancien'); ecrire('vendor/x.js', 'x'); ecrire('app.js', 'x');
r = D.analyser(dir);
assert.deepEqual([r.complet, r.manquants, r.differents, r.enTrop], [false, [], ['public/app.js'], ['app.js', 'vendor']]);
ecrire('public/app.js', 'C'); fs.rmSync(path.join(dir, 'vendor'), { recursive: true }); fs.rmSync(path.join(dir, 'app.js'));
assert.equal(D.analyser(dir).complet, true); assert.deepEqual(D.analyser(dir).enTrop, [], 'data/ toléré');
fs.rmSync(dir, { recursive: true, force: true });
console.log('Diagnostic : manquants, différents, éléments en trop et dossier data vérifiés.');
